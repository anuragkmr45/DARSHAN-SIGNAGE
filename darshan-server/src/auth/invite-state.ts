export const CANONICAL_INVITE_EXPIRY_PATTERN =
  '^([0-9]{4}-(((0[13578]|1[02])-(0[1-9]|[12][0-9]|3[01]))|((0[469]|11)-(0[1-9]|[12][0-9]|30))|(02-(0[1-9]|1[0-9]|2[0-8])))|([0-9]{2}(0[48]|[2468][048]|[13579][26])|([02468][048]|[13579][26])00)-02-29)T([01][0-9]|2[0-3]):[0-5][0-9]:[0-5][0-9]\\.[0-9]{3}Z$';
export const CANONICAL_INVITE_TOKEN_PATTERN = '^[0-9a-fA-F]{32}$';

const canonicalInviteExpiry = new RegExp(CANONICAL_INVITE_EXPIRY_PATTERN);
const canonicalInviteToken = new RegExp(CANONICAL_INVITE_TOKEN_PATTERN);

export function parseInviteToken(value: unknown): string | null {
  if (typeof value !== 'string') return null;
  const normalized = value.trim();
  return canonicalInviteToken.test(normalized) ? normalized.toLowerCase() : null;
}

/** Accept only the exact UTC format generated by Date#toISOString. */
export function parseInviteExpiry(value: unknown): Date | null {
  if (typeof value !== 'string' || !canonicalInviteExpiry.test(value)) return null;
  const parsed = new Date(value);
  if (!Number.isFinite(parsed.getTime()) || parsed.toISOString() !== value) return null;
  return parsed;
}

/** Only accounts with no invitation history or a completed invitation may authenticate. */
export function canAuthenticateInviteState(ext: unknown): boolean {
  if (ext === null || ext === undefined) return true;
  if (typeof ext !== 'object' || Array.isArray(ext)) return false;
  const invite = ext as Record<string, unknown>;
  const hasInviteHistory = ['invite_token', 'invite_status', 'invite_expires_at', 'invited_at']
    .some((key) => Object.prototype.hasOwnProperty.call(invite, key));
  if (!hasInviteHistory) return true;
  return invite.invite_status === 'ACTIVATED' &&
    (invite.invite_token === null || invite.invite_token === undefined);
}
